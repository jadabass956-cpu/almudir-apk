// ═══════════════════════════════════════════════════════════
//  3. LETTERS NORMALIZATION — توحيد الحروف
// ═══════════════════════════════════════════════════════════
function _aiNormalizeLetters(text) {
    return String(text || '')
        // إزالة التشكيل
        .replace(/[\u064B-\u0652\u0640]/g, '')
        // توحيد الألف
        .replace(/[أإآٱ]/g, 'ا')
        // توحيد الياء
        .replace(/[ىئ]/g, 'ي')
        // توحيد الواو
        .replace(/ؤ/g, 'و')
        // توحيد التاء المربوطة
        .replace(/ة/g, 'ه')
        // توحيد الهمزة
        .replace(/ء/g, '')
        .toLowerCase()
        .trim();
}

// ═══════════════════════════════════════════════════════════
//  4. SIMPLE ROOT — استخراج جذر بسيط
// ═══════════════════════════════════════════════════════════
function _aiSimpleRoot(word) {
    if (!word || word.length < 3) return word;
    
    let w = word;
    
    // إزالة ال التعريف
    if (w.startsWith('ال') && w.length > 3) w = w.substring(2);
    
    // إزالة الضمائر في النهاية
    w = w.replace(/(ي|ك|ه|ها|نا|كم|هم|هن)$/, '');
    
    // إزالة النون والتاء للجمع المؤنث
    // "مبيعات" → "مبيع"
    if (w.endsWith('ات') && w.length > 4) w = w.substring(0, w.length - 2);
    
    // "مبيع" من "مبيعات" (بعد حذف 'ات' يبقى "مبيع")
    // "ديون" من "ديني" (بعد حذف 'ي' يبقى "دين")
    
    // أسماء المفعول "م" في البداية
    // مثل "مدفوع" → "دفع"
    // لكن لا نطبقها هنا لأنها تخرب "مبيع", "مصروف"
    
    // إن كانت الكلمة طويلة، حاول إزالة إضافات
    if (w.length > 5) {
        // "صندوقي" → "صندوق"
        // "مشترياتي" → "مشتري"
        // ملاحظة: لن نُطبّق قاعدة قاسية
    }
    
    return w;
}

// ═══════════════════════════════════════════════════════════
//  5. SYNONYM MAPPING — تحويل للمرادف
// ═══════════════════════════════════════════════════════════
const _aiReverseSynonyms = (() => {
    const map = {};
    for (const [canonical, variants] of Object.entries(AI_SYNONYMS)) {
        // الكلمة الأساسية تشير لنفسها
        map[canonical] = canonical;
        // المتغيرات تشير للأساسية
        variants.forEach(v => { map[v] = canonical; });
    }
    return map;
})();

function _aiToCanonical(word) {
    if (!word) return word;
    // بحث مباشر
    if (_aiReverseSynonyms[word]) return _aiReverseSynonyms[word];
    // بعد التطبيع الأساسي
    const norm = _aiNormalizeLetters(word);
    if (_aiReverseSynonyms[norm]) return _aiReverseSynonyms[norm];
    return norm;
}

// ═══════════════════════════════════════════════════════════
//  6. PERIOD EXTRACTION — استخراج الفترة
// ═══════════════════════════════════════════════════════════
function aiExtractPeriod(text) {
    const n = _aiNormalizeLetters(text);
    
    // ✅ FIX-2: استخدام includes بدل \b (لا يعمل مع العربية)
    // الأولوية: الأصغر أولاً
    if (n.includes('اليوم') || n.includes('هلا') || n.includes('حاليا') || 
        n.includes('الان') || n.includes('هسه') || n.includes('هسع') || 
        n.includes('هلق')) return 'today';
    
    if (n.includes('امس') || n.includes('امبارح')) return 'yesterday';
    
    if (n.includes('اسبوع') || n.includes('جمعه')) return 'week';
    
    if (n.includes('شهر')) return 'month';
    
    if (n.includes('سنه') || n.includes('سنة') || n.includes('عام')) return 'year';
    
    if (n.includes('كل') || n.includes('جميع') || n.includes('الكل')) return 'all';
    
    return null;
}

// ═══════════════════════════════════════════════════════════
//  7. MAIN FUNCTION — الدالة الرئيسية
// ═══════════════════════════════════════════════════════════
/**
 * تطبيع متقدم للنص العربي
 * @param {String} text - النص الأصلي
 * @param {Object} options - { keepStopWords, keepPeriod }
 * @returns {String} - نص مطبّع مفصول بمسافات
 */
function aiNorm2(text, options) {
    options = options || {};
    
    if (!text) return '';
    
    // 1) تطبيع الحروف
    let s = _aiNormalizeLetters(text);
    
    // 2) تقسيم لكلمات
    let words = s.split(/[\s،,.؟?!:;()\[\]{}«»"'\-_\/\\]+/)
                 .filter(w => w.length > 1); // نحذف كلمة أحرف واحد
    
    // 3) إزالة stop words
    if (!options.keepStopWords) {
        words = words.filter(w => !AI_STOP_WORDS.has(w));
    }
    
    // 4) الجذر البسيط أولاً (لإزالة "ال" والضمائر)
    // ✅ FIX-4: نقل _aiSimpleRoot قبل AI_PLURALS
    words = words.map(w => _aiSimpleRoot(w));
    
    // 5) توحيد الجمع (بعد الجذر)
    words = words.map(w => AI_PLURALS[w] || w);
    
    // 6) تحويل للمرادف (آخر خطوة)
    words = words.map(w => _aiToCanonical(w));
    
    // 6) إزالة التكرار مع الحفاظ على الترتيب
    const seen = new Set();
    const unique = [];
    words.forEach(w => {
        if (!seen.has(w)) {
            seen.add(w);
            unique.push(w);
        }
    });
    
    return unique.join(' ');
}

// ═══════════════════════════════════════════════════════════
//  8. KEYWORDS EXTRACTION — استخراج كلمات مفتاحية
// ═══════════════════════════════════════════════════════════
function aiExtractKeywords(text) {
    const normalized = aiNorm2(text);
    if (!normalized) return [];
    return normalized.split(/\s+/).filter(w => w.length > 1);
}

// ═══════════════════════════════════════════════════════════
//  9. UTILITY — مقارنة كلمتين
// ═══════════════════════════════════════════════════════════
function aiWordsMatch(a, b) {
    if (!a || !b) return false;
    const na = _aiToCanonical(a);
    const nb = _aiToCanonical(b);
    if (na === nb) return true;
    // مطابقة جزئية
    if (na.length > 3 && nb.length > 3) {
        if (na.includes(nb) || nb.includes(na)) return true;
    }
    return false;
}

